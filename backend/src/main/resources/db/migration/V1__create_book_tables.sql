CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(512) NOT NULL,
    author VARCHAR(255) NOT NULL,
    difficulty VARCHAR(16) NOT NULL,
    source_filename VARCHAR(255) NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    imported_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_book_content_hash UNIQUE (content_hash),
    CONSTRAINT ck_book_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD'))
);

CREATE TABLE book_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL,
    section_key VARCHAR(255) NOT NULL,
    text CLOB NOT NULL,
    type VARCHAR(16) NOT NULL,
    CONSTRAINT fk_section_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT uk_book_section_key UNIQUE (book_id, section_key),
    CONSTRAINT ck_section_type CHECK (type IN ('BEGIN', 'NODE', 'END'))
);

CREATE TABLE book_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL,
    option_position INTEGER NOT NULL,
    description VARCHAR(255) NOT NULL,
    destination_section_id BIGINT NOT NULL,
    consequence_type VARCHAR(16),
    consequence_value INTEGER,
    consequence_text VARCHAR(255),
    CONSTRAINT fk_option_section FOREIGN KEY (section_id) REFERENCES book_sections (id),
    CONSTRAINT fk_option_destination FOREIGN KEY (destination_section_id) REFERENCES book_sections (id),
    CONSTRAINT uk_section_option_position UNIQUE (section_id, option_position),
    CONSTRAINT ck_option_position CHECK (option_position >= 0),
    CONSTRAINT ck_option_consequence CHECK (
        (consequence_type IS NULL AND consequence_value IS NULL AND consequence_text IS NULL)
        OR (consequence_type IS NOT NULL
            AND consequence_type IN ('LOSE_HEALTH', 'GAIN_HEALTH')
            AND consequence_value IS NOT NULL AND consequence_value > 0
            AND consequence_text IS NOT NULL)
    )
);
